// Builds js/pinyin-data.js: the toned pinyin of every CJK Unified Ideograph (U+4E00–U+9FFF),
// from macOS's own Mandarin→Latin transliterator (CFStringTransform). Run on a Mac:
//   swift web/tools/gen-pinyin.swift > web/js/pinyin-data.js
// Each character gets its most common reading; the page lets you fix the rest by tapping.
import Foundation

let marks: [UInt32: Int] = [0x304: 1, 0x301: 2, 0x30C: 3, 0x300: 4]
var groups: [String: [Character]] = [:]
var order: [String] = []
for cp in 0x4E00...0x9FFF {
  guard let scalar = Unicode.Scalar(cp) else { continue }
  let ch = Character(scalar)
  let m = NSMutableString(string: String(ch))
  CFStringTransform(m, nil, kCFStringTransformMandarinLatin, false)
  let latin = (m as String).trimmingCharacters(in: .whitespaces)
  if latin == String(ch) || latin.isEmpty || latin.contains(" ") { continue }
  var tone = 5 // neutral
  var plain = ""
  for u in latin.decomposedStringWithCanonicalMapping.unicodeScalars {
    if let t = marks[u.value] { tone = t; continue }
    if u.value == 0x308 { plain += "v"; plain = plain.replacingOccurrences(of: "uv", with: "v"); continue }
    plain.unicodeScalars.append(u)
  }
  plain = plain.lowercased()
  guard plain.range(of: "^[a-z]+$", options: .regularExpression) != nil else { continue }
  let key = "\(plain)\(tone)"
  if groups[key] == nil { groups[key] = []; order.append(key) }
  groups[key]!.append(ch)
}
order.sort()
print("// Generated by tools/gen-pinyin.swift from macOS's Mandarin transliterator. Do not edit by hand.")
print("// Format: \"syllable+tone:characters\" entries joined by spaces (tone 5 = neutral, v = ü).")
print("(function (root) {")
print("  'use strict';")
print("  const DATA = '" + order.map { "\($0):\(String(groups[$0]!))" }.joined(separator: " ") + "';")
print("  root.PinyinData = DATA;")
print("  if (typeof module !== 'undefined' && module.exports) module.exports = DATA;")
print("})(typeof window !== 'undefined' ? window : globalThis);")
